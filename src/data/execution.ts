/** Les deux images (départ, arrivée) d'un exercice du catalogue, ou rien s'il n'a pas de démonstration. */
export function executionImages(catalogId?: string): [string, string] | undefined {
  const src = catalogId ? EXECUTION_SOURCE[catalogId] : undefined
  if (!src) return undefined
  const base = `${import.meta.env.BASE_URL}exec/${src}`
  return [`${base}_0.webp`, `${base}_1.webp`]
}
